const { app, BrowserWindow } = require('electron')
const { build } = require('esbuild')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
app.disableHardwareAcceleration()
app.whenReady().then(async () => {
  const output = path.join(app.getPath('temp'), 'ynot-project-wizard-qa')
  await fs.mkdir(output, {recursive:true})
  const result = await build({stdin:{contents:`import React from 'react';import{createRoot}from'react-dom/client';import Wizard from './src/components/NewProjectWizard';createRoot(document.getElementById('root')).render(<Wizard bare onClose={()=>{}} onSubmit={opts=>window.submitted=opts}/>);`,resolveDir:process.cwd(),loader:'tsx'},bundle:true,platform:'browser',write:false,loader:{'.png':'dataurl','.icc':'dataurl'}})
  await fs.writeFile(path.join(output,'fixture.js'),result.outputFiles[0].text)
  await fs.copyFile('src/styles/app.css',path.join(output,'app.css'))
  await fs.writeFile(path.join(output,'index.html'),'<html><head><link rel="stylesheet" href="app.css"></head><body><div id="root"></div><script src="fixture.js"></script></body></html>')
  const win = new BrowserWindow({show:false,frame:false,width:1060,height:840,webPreferences:{offscreen:true}})
  await win.loadFile(path.join(output,'index.html'))
  const evaluate = code => win.webContents.executeJavaScript(`(() => eval(${JSON.stringify(code)}))()`)
  for(let i=0;i<40&&!await evaluate('!!document.querySelector(".project-wizard")');i++) await new Promise(r=>setTimeout(r,100))
  for(const [width,height] of [[720,480],[1060,840],[1920,1080]]) {
    win.setSize(width,height)
    await new Promise(r=>setTimeout(r,200))
    for(const tab of ['Album Company Preset','Custom']) {
      await evaluate(`Array.from(document.querySelectorAll('[role=tab]')).find(e=>e.textContent===${JSON.stringify(tab)}).click()`)
      await new Promise(r=>setTimeout(r,80))
      assert.ok(await evaluate('document.body.scrollWidth<=innerWidth'), 'No horizontal overflow')
      assert.ok(await evaluate('document.querySelector(".modal-card__footer").getBoundingClientRect().bottom<=innerHeight+1'), 'Next stays visible')
      assert.ok(await evaluate('document.querySelector(".modal-card__body").clientHeight>100'), 'Form remains scrollable')
      await fs.writeFile(path.join(output,`${width}-${tab.startsWith('Custom')?'custom':'company'}.png`),(await win.webContents.capturePage()).toPNG())
    }
    await evaluate(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Next').click()`)
    await new Promise(r=>setTimeout(r,100))
    assert.equal(await evaluate('document.querySelectorAll(".library-preview").length'),10)
    assert.ok(await evaluate('document.querySelector(".modal-card__footer").getBoundingClientRect().bottom<=innerHeight+1'),'Appearance footer stays visible')
    assert.ok(await evaluate('document.body.scrollWidth<=innerWidth'))
    assert.equal(await evaluate('document.querySelector(".modal-card__body").scrollTop'),0,'New step begins at the top')
    await fs.writeFile(path.join(output,`${width}-appearance.png`),(await win.webContents.capturePage()).toPNG())
    await evaluate(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Back').click()`)
    await new Promise(r=>setTimeout(r,100))
  }
  const choices=await evaluate(`Array.from(document.querySelectorAll('select')).filter(s=>s.parentElement.textContent.includes('Starts with')||s.parentElement.textContent.includes('Ends with')).map(s=>Array.from(s.options,o=>o.textContent))`)
  assert.deepEqual(choices,[['Full spread','Single page/side'],['Full spread','Single page/side']])
  await evaluate(`const input=Array.from(document.querySelectorAll('label')).find(e=>e.textContent.includes('Spread width')).querySelector('input');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'18');input.dispatchEvent(new Event('input',{bubbles:true}))`)
  await new Promise(r=>setTimeout(r,100))
  await evaluate(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Next').click()`)
  await new Promise(r=>setTimeout(r,100))
  for (const [filter,excluded] of [['all',[]],['no-square',[1,2,4,5]],['only-3x2',[1,2,4,5,6,7,8]]]) {
    await evaluate(`const select=document.querySelector('.library-appearance__filter select');select.value=${JSON.stringify(filter)};select.dispatchEvent(new Event('change',{bubbles:true}))`)
    await new Promise(r=>setTimeout(r,100))
    assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('.library-preview')).flatMap((e,i)=>e.classList.contains('is-excluded')?[i]:[])`),excluded,filter)
  }
  win.setSize(1060,840)
  for(let i=0;i<30;i++){if(await evaluate('innerWidth===1060 && innerHeight===840'))break;await new Promise(r=>setTimeout(r,100))}
  await new Promise(r=>setTimeout(r,150))
  await fs.writeFile(path.join(output,'filtered-appearance.png'),(await win.webContents.capturePage()).toPNG())
  assert.ok(await evaluate('document.querySelector(".template-preview-grid").children.length>0'))
  const beforeGap = await evaluate('document.querySelector(".gallery-cell").style.width')
  await evaluate(`const s=document.querySelector('[aria-label="Gap between images"]');s.value='Thick';s.dispatchEvent(new Event('change',{bubbles:true}))`)
  await new Promise(r=>setTimeout(r,100))
  assert.notEqual(await evaluate('document.querySelector(".gallery-cell").style.width'),beforeGap)
  await evaluate(`const s=document.querySelector('[aria-label="Border around images"]');s.value='Medium';s.dispatchEvent(new Event('change',{bubbles:true}))`)
  await new Promise(r=>setTimeout(r,100))
  assert.ok(await evaluate('parseFloat(getComputedStyle(document.querySelector(".gallery-cell")).borderTopWidth)>0'))
  await evaluate(`Array.from(document.querySelectorAll('button')).find(e=>e.textContent.includes('Start')).click()`)
  await new Promise(r=>setTimeout(r,100))
  assert.equal(await evaluate('window.submitted.layoutStart'),'spread')
  assert.equal(await evaluate('window.submitted.size.widthIn'),18)
  assert.equal(await evaluate('window.submitted.defaultGapPx'),28)
  assert.equal(await evaluate('window.submitted.defaultBorderWidth'),5)
  assert.ok(await evaluate('window.submitted.enabledTemplateIds.length>0'))
  assert.ok(await evaluate('window.submitted.enabledTemplateIds.length<9000'))
  assert.equal(await evaluate('window.submitted.includeFullSpreadTemplates'),true)
  console.log('Wizard checks passed: three viewport sizes, both tabs, dropdown choices, appearance and creation payload.',output)
  win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
