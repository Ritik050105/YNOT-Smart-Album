const assert=require('node:assert/strict'),{buildSync}=require('esbuild'),Module=require('node:module');
const bundle=buildSync({entryPoints:['src/state/preferences.ts'],bundle:true,platform:'node',format:'cjs',write:false});
const loaded=new Module(__filename);loaded._compile(bundle.outputFiles[0].text,__filename);
const {preferenceDefaults,previewGapPresetImport,importGapPresets,exportGapPresets}=loaded.exports;
const snapshot=exportGapPresets(preferenceDefaults,false);
const current={...preferenceDefaults,projectDirectory:'C:/Albums',gapImportPast:[snapshot],gapImportFuture:[snapshot]};
const original=JSON.stringify(current);
const legacy=importGapPresets(snapshot);
assert.deepEqual(previewGapPresetImport(current,legacy),current,'Identical legacy import preserves histories');
const changed={...legacy,gapPercentPresets:[-40,-20,20,40]};
const result=previewGapPresetImport(current,changed);
assert.deepEqual(result.gapImportPast,[snapshot,exportGapPresets(current,false)]);
assert.deepEqual(result.gapImportFuture,[]);
assert.equal(result.projectDirectory,current.projectDirectory);
assert.deepEqual(result.gapPercentPresets,changed.gapPercentPresets);
const transferred={...changed,gapImportPast:[snapshot,snapshot],gapImportFuture:[snapshot]};
const transferredBefore=JSON.stringify(transferred);
const preview=previewGapPresetImport(current,transferred);
assert.deepEqual(preview.gapImportPast,[snapshot,snapshot,exportGapPresets(current,false)]);
assert.deepEqual(preview.gapImportFuture,[snapshot]);
assert.equal(JSON.stringify(current),original,'Preview must not mutate current preferences');
assert.equal(JSON.stringify(transferred),transferredBefore,'Preview must not mutate the import');
const empty=previewGapPresetImport(current,{...legacy,gapImportPast:[],gapImportFuture:[]});
assert.deepEqual(empty.gapImportPast,[exportGapPresets(current,false)]);
assert.deepEqual(empty.gapImportFuture,[]);
console.log('Import comparison passed: exact resulting histories, legacy no-op, legacy replacement, transferred/empty histories, untouched input and unrelated settings');

const {summarizeGapPresetImport}=loaded.exports;
assert.ok(summarizeGapPresetImport(current,current).every(row=>row.added===0&&row.changed===0&&row.removed===0));
const a=[-25,-10,10,25],b=[-40,-20,20,40],c=[-50,-5,5,50];
const counts=summarizeGapPresetImport({...current,gapPresetPast:[a,b],gapPresetFuture:[a]}, {...current,gapPercentPresets:b,gapPresetPast:[c,a,b],gapPresetFuture:[]});
assert.deepEqual(counts.slice(0,3),[{label:'Presets',added:0,changed:4,removed:0},{label:'Preset Undo',added:1,changed:0,removed:0},{label:'Preset Redo',added:0,changed:0,removed:1}]);
const changedCounts=summarizeGapPresetImport({...current,gapImportPast:[snapshot]}, {...current,gapImportPast:[JSON.stringify(JSON.parse(snapshot)),exportGapPresets({...current,gapPercentPresets:b},false)]});
assert.deepEqual(changedCounts[3],{label:'Import Undo',added:1,changed:1,removed:0});
assert.equal(JSON.stringify(current),original);
console.log('Summary counts passed: additions, replacements, removals, semantic snapshots and no mutation');
