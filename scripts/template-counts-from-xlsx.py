"""Reads "YNOT Album Templates Count.xlsx" (a sheet of how many templates every photo mix needs) and writes the two combination files:

  docs/template-counts.json   the machine-readable table  { album, rows: [{photos, horizontal, vertical, templates}] }
  docs/template-counts.md     the same as a table to read

  python scripts/template-counts-from-xlsx.py "C:/Users/me/Downloads/YNOT Album Templates Count.xlsx"

The workbook is read straight from its XML (it is a zip), so no spreadsheet library is needed. src/engine/templateCounts.ts holds the same numbers
for the app; scripts/test-template-counts.mjs checks the two agree.
"""
import json, re, sys, zipfile, xml.etree.ElementTree as ET
from pathlib import Path

path = sys.argv[1] if len(sys.argv) > 1 else r'C:/Users/ritik/Downloads/YNOT Album Templates Count.xlsx'
ns = {'m': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
z = zipfile.ZipFile(path)
strings = []
if 'xl/sharedStrings.xml' in z.namelist():
    for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall('m:si', ns):
        strings.append(''.join(t.text or '' for t in si.iter('{%s}t' % ns['m'])))
sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
album, rows = None, []
for row in sheet.find('m:sheetData', ns).findall('m:row', ns):
    values = []
    for c in row.findall('m:c', ns):
        v = c.find('m:v', ns)
        values.append((strings[int(v.text)] if c.get('t') == 's' else v.text) if v is not None else None)
    present = [x for x in values if x is not None]
    if len(present) == 1 and not re.fullmatch(r'\d+', present[0]):
        album = present[0]
    elif len(values) >= 4 and all(x is not None and re.fullmatch(r'\d+', x) for x in values[:4]):
        rows.append({'photos': int(values[0]), 'horizontal': int(values[1]), 'vertical': int(values[2]), 'templates': int(values[3])})
assert rows and all(r['horizontal'] + r['vertical'] == r['photos'] for r in rows), 'unexpected sheet layout'
root = Path(__file__).resolve().parent.parent / 'docs'
(root / 'template-counts.json').write_text(json.dumps({'album': album, 'source': 'YNOT Album Templates Count.xlsx', 'rows': rows}, indent=1), encoding='utf-8')
lines = [
    '# Templates required for each photo combination',
    '',
    f'From **YNOT Album Templates Count.xlsx** (album `{album}`): for every number of photographs (1 to 24) and every mix of horizontal and vertical ones, how many templates the browser must offer.',
    f'{len(rows)} combinations, {sum(r["templates"] for r in rows):,} templates in all. Generated by `scripts/template-counts-from-xlsx.py`; the app reads the same numbers from `src/engine/templateCounts.ts`.',
    '',
    '| Photos | Horizontal | Vertical | Templates required |',
    '|---:|---:|---:|---:|',
]
lines += [f'| {r["photos"]} | {r["horizontal"]} | {r["vertical"]} | {r["templates"]} |' for r in rows]
(root / 'template-counts.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(album, len(rows), 'combinations,', sum(r['templates'] for r in rows), 'templates')
